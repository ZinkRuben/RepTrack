inserted AS (
    INSERT INTO exercises (name, category, primary_muscle, cardio_type, description,
                           tracks_weight, tracks_reps, tracks_duration, tracks_distance, tracks_heart_rate)
    SELECT name, category, primary_muscle, cardio_type, description,
           tracks_weight, tracks_reps, tracks_duration, tracks_distance, tracks_heart_rate
    FROM seed
    RETURNING id, name
)
INSERT INTO exercise_secondary_muscles (exercise_id, muscle)
SELECT i.id, m.muscle
FROM inserted i
JOIN seed s ON s.name = i.name
CROSS JOIN LATERAL unnest(s.secondary_muscles) AS m(muscle);
